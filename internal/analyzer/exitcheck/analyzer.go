// Package exitcheck checks panic and the permitted locations of process termination.
package exitcheck

import (
	"go/ast"
	"go/types"
	"strings"

	"golang.org/x/tools/go/analysis"
	"golang.org/x/tools/go/types/typeutil"
)

// Analyzer reports builtin panic, os.Exit in main.main, and log.Fatal/Fatalf/Fatalln
// outside main.main.
var Analyzer = &analysis.Analyzer{
	Name: "exitcheck",
	Doc:  "report builtin panic, os.Exit in main.main and log.Fatal calls outside main.main",
	Run:  run,
}

func run(pass *analysis.Pass) (any, error) {
	for _, file := range pass.Files {
		if isTestHarness(pass, file) {
			continue
		}
		ast.Walk(visitor{pass: pass}, file)
	}
	return nil, nil
}

func isTestHarness(pass *analysis.Pass, file *ast.File) bool {
	if pass.Pkg.Name() != "main" || !strings.HasSuffix(pass.Pkg.Path(), ".test") {
		return false
	}
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if comment.Text == "// Code generated by 'go test'. DO NOT EDIT." {
				return true
			}
		}
	}
	return false
}

type visitor struct {
	pass   *analysis.Pass
	inMain bool
}

// A value receiver keeps the enclosing function's context for sibling nodes.
func (v visitor) Visit(node ast.Node) ast.Visitor {
	switch node := node.(type) {
	case *ast.FuncDecl:
		v.inMain = v.pass.Pkg.Name() == "main" && node.Name.Name == "main" && node.Recv == nil
	case *ast.FuncLit:
		v.inMain = false
	case *ast.CallExpr:
		v.checkCall(node)
	}
	return v
}

func (v visitor) checkCall(call *ast.CallExpr) {
	switch obj := typeutil.Callee(v.pass.TypesInfo, call).(type) {
	case *types.Builtin:
		if obj.Name() == "panic" {
			v.pass.Reportf(call.Pos(), "use of builtin panic is forbidden")
		}
	case *types.Func:
		if obj.Pkg() == nil || obj.Signature().Recv() != nil {
			return
		}
		switch obj.Pkg().Path() {
		case "log":
			if !v.inMain && (obj.Name() == "Fatal" || obj.Name() == "Fatalf" || obj.Name() == "Fatalln") {
				v.pass.Reportf(call.Pos(), "log.%s is only allowed in main.main", obj.Name())
			}
		case "os":
			if v.inMain && obj.Name() == "Exit" {
				v.pass.Reportf(call.Pos(), "os.Exit is forbidden in main.main")
			}
		}
	}
}
