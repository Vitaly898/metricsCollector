package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"sort"

	"golang.org/x/tools/go/packages"
)

const (
	generatedFile = "reset.gen.go"
	generatedMark = "// Code generated by reset. DO NOT EDIT."
)

type resetTarget struct {
	name   string
	named  *types.Named
	fields *types.Struct
}

type outputFile struct {
	path string
	data []byte
}

func generate(dir string) error {
	overlay, err := prepareOverlay(dir)
	if err != nil {
		return err
	}
	pkgs, err := packages.Load(&packages.Config{Dir: dir, Mode: packages.LoadSyntax, Overlay: overlay}, "./...")
	if err != nil {
		return fmt.Errorf("load packages: %w", err)
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("no Go packages found in %s", dir)
	}
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].PkgPath < pkgs[j].PkgPath })

	// Prepare and validate all results before changing any source files.
	var outputs []outputFile
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			return fmt.Errorf("load package %s: %s", pkg.PkgPath, pkg.Errors[0])
		}
		targets, err := collectTargets(pkg)
		if err != nil {
			return err
		}
		path := filepath.Join(pkg.Dir, generatedFile)
		previous, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("read %s: %w", path, err)
		}
		if len(targets) == 0 && !bytes.HasPrefix(previous, []byte(generatedMark+"\n")) {
			continue
		}
		if err == nil && !bytes.HasPrefix(previous, []byte(generatedMark+"\n")) {
			return fmt.Errorf("refusing to overwrite %s: file was not generated by reset", path)
		}
		data, err := renderPackage(pkg.Types, targets)
		if err != nil {
			return fmt.Errorf("generate package %s: %w", pkg.PkgPath, err)
		}
		if !bytes.Equal(previous, data) {
			outputs = append(outputs, outputFile{path: path, data: data})
		}
	}
	for _, output := range outputs {
		if err := os.WriteFile(output.path, output.data, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", output.path, err)
		}
	}
	return nil
}
