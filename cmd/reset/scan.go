// The type checker sees current method stubs instead of the old generated code.
// This also allows callers to use Reset before the first generation.
func prepareOverlay(dir string) (map[string][]byte, error) {
	pkgs, err := packages.Load(&packages.Config{Dir: dir, Mode: packages.LoadFiles}, "./...")
	if err != nil {
		return nil, fmt.Errorf("list packages: %w", err)
	}
	overlay := make(map[string][]byte)
	for _, pkg := range pkgs {
		path := filepath.Join(pkg.Dir, generatedFile)
		previous, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		owned := bytes.HasPrefix(previous, []byte(generatedMark+"\n"))
		var specs []*ast.TypeSpec
		manual := make(map[string]bool)
		fset := token.NewFileSet()
		for _, filename := range pkg.CompiledGoFiles {
			if filename == path && owned {
				continue
			}
			file, err := parser.ParseFile(fset, filename, nil, parser.ParseComments)
			if err != nil {
				return nil, fmt.Errorf("parse %s: %w", filename, err)
			}
			specs = append(specs, markedTypes(file)...)
			for _, decl := range file.Decls {
				method, ok := decl.(*ast.FuncDecl)
				if ok && method.Name.Name == "Reset" && method.Recv != nil && len(method.Recv.List) == 1 {
					manual[receiverName(method.Recv.List[0].Type)] = true
				}
			}
		}
		var stubs bytes.Buffer
		for _, spec := range specs {
			if spec.Assign.IsValid() {
				return nil, fmt.Errorf("%s: generate:reset requires a defined struct type", fset.Position(spec.Pos()))
			}
			if structure, ok := spec.Type.(*ast.StructType); ok {
				for _, field := range structure.Fields.List {
					for _, name := range field.Names {
						if name.Name == "Reset" {
							return nil, fmt.Errorf("%s: field conflicts with the generated method", fset.Position(name.Pos()))
						}
					}
				}
			}
			if !manual[spec.Name.Name] {
				var params []string
				if spec.TypeParams != nil {
					for _, field := range spec.TypeParams.List {
						for _, name := range field.Names {
							params = append(params, name.Name)
						}
					}
				}
				fmt.Fprintf(&stubs, "func (_ *%s%s) Reset() {}\n", spec.Name.Name, typeArguments(params))
			}
		}
		if stubs.Len() == 0 && !owned {
			continue
		}
		if len(previous) != 0 && !owned {
			return nil, fmt.Errorf("refusing to overwrite %s: file was not generated by reset", path)
		}
		overlay[path] = fmt.Appendf(nil, "%s\npackage %s\n%s", generatedMark, pkg.Name, stubs.Bytes())
	}
	return overlay, nil
}

func collectTargets(pkg *packages.Package) ([]resetTarget, error) {
	var targets []resetTarget
	for _, file := range pkg.Syntax {
		if filepath.Base(pkg.Fset.Position(file.Pos()).Filename) == generatedFile {
			continue
		}
		for _, spec := range markedTypes(file) {
			position := pkg.Fset.Position(spec.Pos())
			obj := pkg.TypesInfo.Defs[spec.Name]
			named, ok := obj.Type().(*types.Named)
			if !ok {
				return nil, fmt.Errorf("%s: generate:reset requires a defined struct type", position)
			}
			fields, ok := named.Underlying().(*types.Struct)
			if !ok {
				return nil, fmt.Errorf("%s: generate:reset requires a struct type", position)
			}
			manual := false
			for i := 0; i < named.NumMethods(); i++ {
				method := named.Method(i)
				if method.Name() == "Reset" && filepath.Base(pkg.Fset.Position(method.Pos()).Filename) != generatedFile {
					if !isReset(method) {
						return nil, fmt.Errorf("%s: existing Reset must have no parameters or results", position)
					}
					manual = true
				}
			}
			if !manual {
				targets = append(targets, resetTarget{name: spec.Name.Name, named: named, fields: fields})
			}
		}
	}
	sort.Slice(targets, func(i, j int) bool { return targets[i].name < targets[j].name })
	return targets, nil
}

func markedTypes(file *ast.File) []*ast.TypeSpec {
	var specs []*ast.TypeSpec
	for _, decl := range file.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok || group.Tok != token.TYPE {
			continue
		}
		for _, spec := range group.Specs {
			typeSpec := spec.(*ast.TypeSpec)
			if hasResetMarker(group.Doc) || hasResetMarker(typeSpec.Doc) {
				specs = append(specs, typeSpec)
			}
		}
	}
	return specs
}

func hasResetMarker(group *ast.CommentGroup) bool {
	if group != nil {
		for _, comment := range group.List {
			if strings.TrimSpace(comment.Text) == "// generate:reset" {
				return true
			}
		}
	}
	return false
}

func receiverName(expr ast.Expr) string {
	switch expr := ast.Unparen(expr).(type) {
	case *ast.Ident:
		return expr.Name
	case *ast.StarExpr:
		return receiverName(expr.X)
	case *ast.IndexExpr:
		return receiverName(expr.X)
	case *ast.IndexListExpr:
		return receiverName(expr.X)
	}
	return ""
}

func typeArguments(names []string) string {
	if len(names) == 0 {
		return ""
	}
	return "[" + strings.Join(names, ", ") + "]"
}

func isReset(method *types.Func) bool {
	sig := method.Signature()
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}
